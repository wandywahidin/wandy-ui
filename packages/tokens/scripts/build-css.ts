import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { colorKeys, tokens, type Tokens } from '../src/tokens'

/**
 * Emit theme.css: runtime variables (`--wui-*`) for light and `.dark`, and a
 * Tailwind v4 `@theme inline` block that maps utilities (`bg-primary`, ...) onto them.
 * Consumers re-theme by overriding `--wui-*`; no rebuild needed.
 */
export function buildCss(t: Tokens): string {
  const vars = (mode: 'light' | 'dark') =>
    colorKeys.map((k) => `  --wui-${k}: ${t[mode][k]};`).join('\n')

  const theme = [
    ...colorKeys.map((k) => `  --color-${k}: var(--wui-${k});`),
    `  --radius-sm: ${t.radius.sm};`,
    `  --radius-md: ${t.radius.md};`,
    `  --radius-lg: ${t.radius.lg};`,
    `  --font-sans: ${t.font.sans};`,
    `  --shadow-sm: ${t.shadow.sm};`,
    `  --shadow-md: ${t.shadow.md};`,
    `  --shadow-lg: ${t.shadow.lg};`,
  ].join('\n')

  return [
    '/* Generated by @wandy29/tokens. Do not edit by hand. */',
    `:root {\n${vars('light')}\n  color-scheme: light;\n}`,
    `.dark {\n${vars('dark')}\n  color-scheme: dark;\n}`,
    '@custom-variant dark (&:where(.dark, .dark *));',
    `@theme inline {\n${theme}\n}`,
    '',
  ].join('\n\n')
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  const out = resolve(dirname(fileURLToPath(import.meta.url)), '../dist/theme.css')
  mkdirSync(dirname(out), { recursive: true })
  writeFileSync(out, buildCss(tokens))
  console.log(`wrote ${out}`)
}
